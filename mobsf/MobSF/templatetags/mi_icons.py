@register.simple_tag
def icon(name, size=20, **kwargs):
    """Render an inline Lucide SVG icon.

    Unknown icon names render an empty 'help-circle' so the layout
    doesn't break in development.
    """
    paths = ICON_PATHS.get(name) or ICON_PATHS['help-circle']
    extra_class = kwargs.get('class', '')
    stroke_width = kwargs.get('stroke', '1.5')
    aria_label = kwargs.get('label', '')
    aria = (
        f' role="img" aria-label="{aria_label}"' if aria_label
        else ' aria-hidden="true"'
    )
    return mark_safe(
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="none" stroke="currentColor" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round" '
        f'class="inline-block flex-shrink-0 {extra_class}"{aria}>'
        f'{paths}'
        f'</svg>',
    )
